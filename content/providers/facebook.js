// Facebook provider for Clearbook
//
// Design notes (Facebook's markup is obfuscated and changes constantly):
// - Never rely on class names. Use ARIA roles, data-pagelet, hrefs and
//   visible label text, which Facebook has to keep stable for accessibility.
// - Text matching is done in JS (CSS has no :contains()).
// - Only whole feed units are hidden, never their ancestors, and a safety
//   guard refuses to hide anything that contains the main page structure.
// - DOM work is batched/debounced; Facebook mutates the DOM constantly.
const FacebookProvider = {
  name: 'facebook',

  // Exact (case-insensitive) label texts that Facebook shows in the header
  // of non-friend feed units. Matched against short text elements only.
  labels: {
    sponsored: ['Sponsored', 'Paid partnership', 'Promoted'],
    // Also matched, but only when reached through the hidden-reference tricks
    // (aria-labelledby / SVG <use>): "Ad" is too short to trust as plain text.
    sponsoredReferenced: ['Sponsored', 'Paid partnership', 'Promoted', 'Ad'],
    suggested: [
      'Suggested for you', 'Suggested post', 'Suggested posts',
      'Recommended for you', 'Recommended post', 'Because you viewed a similar post',
    ],
    peopleYouMayKnow: ['People you may know', 'People You May Know'],
    reels: ['Reels', 'Reels and short videos', 'Suggested reels'],
    suggestedGroups: [
      'Suggested groups', 'Suggested group', 'Groups you might like',
      'Your group suggestions', 'Group suggestions', 'Suggested for you in groups',
    ],
    suggestedPages: ['Suggested pages', 'Pages you may like', 'Suggested page'],
    ai: ['AI info', 'Made with AI', 'AI-generated', 'Generated by AI', 'Created with AI'],
    // Shown next to authors you are not friends with / don't follow.
    nonFriend: ['Follow', 'Join', 'Join group'],
  },

  // Structural markers (no text matching needed).
  markers: {
    sponsored: [
      'a[href*="/ads/about"]',
      'a[href^="/ads/"]',
      '[aria-label="Sponsored"]',
      // NOT [data-ad-preview] / [data-ad-comet-preview]: despite the name,
      // Facebook puts data-ad-preview="message" on the text of every post.
      // Attribution Reporting API attribute, used on ad links.
      'a[attributionsrc]',
      // Ad menus are labelled "Open menu for <advertiser> sponsored content".
      '[aria-label*="sponsored content" i]',
    ],
    reels: ['[data-pagelet*="Reels"]', 'div[aria-label="Reels"]'],
    peopleYouMayKnow: ['[data-pagelet*="PeopleYouMayKnow"]'],
  },

  // Standalone regions (not feed units) hidden directly.
  regions: {
    stories: [
      '[data-pagelet*="Stories"]',
      '[role="region"][aria-label="Stories"]',
      'div[aria-label="Stories"]',
    ],
  },

  // Navigation shortcuts. Only matched inside nav/banner so links inside
  // friends' posts are never touched.
  navLinks: {
    marketplace: 'a[href*="/marketplace"]',
    watch: 'a[href*="/watch"]',
    reels: 'a[href*="/reel"]',
  },

  // Elements that must never be hidden (or contain something hidden).
  protectedSelector: 'html, body, [role="main"], [role="feed"], [role="banner"], [role="navigation"]',

  settings: null,
  providerSettings: null,
  keywordBlacklist: [],
  observer: null,
  scheduled: false,
  fastScheduled: false,
  // Nodes touched since the last animation frame (see scheduleFast).
  pendingTargets: new Set(),
  pendingAdded: new Set(),
  // Units waiting for the fast / thorough pass (carried over when a pass
  // runs out of time).
  fastQueue: new Set(),
  slowQueue: new Set(),
  // Unit -> time of its last fast-pass check.
  lastFastCheck: new WeakMap(),
  // Feed unit -> element count at its last thorough check. Lets us skip
  // units that haven't changed while re-checking ones filled in lazily.
  checked: new WeakMap(),
  // Unit -> when we first saw it. Posts are only fast-checked while young.
  firstSeen: new WeakMap(),
  // Units that are old enough and passed a thorough check: never re-checked
  // (until settings change). Without this, posts that keep changing
  // (videos, live counters, comments) would be re-checked forever.
  settled: new WeakSet(),
  // Node -> its unit (or null), so the thousands of mutation targets per
  // second don't each need a DOM walk.
  unitCache: new WeakMap(),
  // Whether the legacy role="feed"/FeedUnit layout is present at all.
  hasLegacyLayout: false,

  async init(settings) {
    this.applySettings(settings);
    // Before the page renders, so the home feed isn't loaded for nothing.
    this.maybeRedirectToFriendsFeed();
    await whenBodyReady();
    this.startObserving();
    this.scheduleClean();
  },

  applySettings(settings) {
    this.settings = settings;
    this.providerSettings = settings.providers.facebook;
    this.keywordBlacklist = (settings.keywordBlacklist || [])
      .map(k => String(k).trim().toLowerCase())
      .filter(Boolean);
  },

  // Two passes, designed to stay out of Facebook's way:
  // - Fast pass (requestAnimationFrame, runs before paint): only posts that
  //   just changed, only cheap checks (markers and exact labels; no layout
  //   reads), and at most FAST_BUDGET_MS per frame. New ads are hidden
  //   before they're drawn without slowing down Facebook's rendering.
  // - Thorough pass (requestIdleCallback, runs when Facebook is idle): all
  //   checks, including the layout-reading obfuscation check and keyword
  //   matching, plus the sidebar/nav/regions. Works in small slices that
  //   yield whenever the browser needs the main thread back.
  startObserving() {
    this.lastUrl = location.href;
    this.observer = new MutationObserver(mutations => {
      // Facebook navigates without page loads (e.g. clicking Home), so
      // watch for URL changes here too.
      if (location.href !== this.lastUrl) {
        this.lastUrl = location.href;
        this.maybeRedirectToFriendsFeed();
      }
      for (const m of mutations) {
        this.pendingTargets.add(m.target);
        m.addedNodes.forEach(n => { if (n.nodeType === 1) this.pendingAdded.add(n); });
      }
      this.scheduleFast();
      this.scheduleClean();
    });
    this.observer.observe(document.body, { childList: true, subtree: true });
    this.interval = setInterval(() => this.scheduleClean(), 3000);
  },

  scheduleFast() {
    if (this.fastScheduled) return;
    this.fastScheduled = true;
    requestAnimationFrame(() => {
      this.fastScheduled = false;
      try {
        this.cleanChanged();
      } catch (e) {
        console.error('Clearbook: fast clean failed', e);
      }
    });
  },

  // Fast pass. Mutation targets are only looked at upwards (a target may be
  // the whole feed list); newly added subtrees are also searched for posts.
  cleanChanged() {
    const ps = this.providerSettings;
    const targets = this.pendingTargets;
    const added = this.pendingAdded;
    this.pendingTargets = new Set();
    this.pendingAdded = new Set();
    if (!ps || !ps.enabled) return;

    const units = this.fastQueue;
    const add = unit => { if (unit) units.add(unit); };
    targets.forEach(node => { if (node.isConnected) add(this.unitFor(node)); });
    added.forEach(node => {
      if (!node.isConnected) return;
      add(this.unitFor(node));
      node.querySelectorAll('[aria-posinset], [data-pagelet^="FeedUnit"]')
        .forEach(el => add(this.unitFor(el)));
    });

    const now = performance.now();
    const deadline = now + FAST_BUDGET_MS;
    const toHide = [];
    for (const unit of units) {
      if (performance.now() > deadline) break;  // rest continues next frame
      units.delete(unit);
      if (!unit.isConnected || unit.hasAttribute('data-clearbook-hidden')) continue;
      if (this.settled.has(unit) || now - this.seen(unit, now) > SETTLE_MS) continue;
      // A post being filled in changes every frame; re-check it at most every
      // FAST_RECHECK_MS (the thorough pass catches anything in between).
      const last = this.lastFastCheck.get(unit);
      if (last !== undefined && now - last < FAST_RECHECK_MS) continue;
      this.lastFastCheck.set(unit, now);

      const reason = this.classifyUnit(unit, false);
      if (reason) toHide.push([unit, reason]);
    }
    toHide.forEach(([unit, reason]) => this.hide(unit, reason, true));
    if (units.size > 0) this.scheduleFast();
  },

  scheduleClean() {
    if (this.scheduled) return;
    this.scheduled = true;
    setTimeout(() => whenIdle(deadline => {
      this.scheduled = false;
      try {
        this.cleanFeed(deadline);
      } catch (e) {
        console.error('Clearbook: cleanFeed failed', e);
      }
    }), 1000);
  },

  // Thorough pass. Units unchanged since their last thorough check are
  // skipped; the rest are processed in idle-time slices.
  cleanFeed(deadline) {
    const ps = this.providerSettings;
    if (!ps || !ps.enabled) return;

    this.cleanRegions();
    this.cleanNavLinks();
    this.cleanSidebarAds();
    this.hasLegacyLayout = document.querySelector(this.legacyUnitSelector) !== null;
    this.getFeedUnits().forEach(unit => {
      if (!this.settled.has(unit)) this.slowQueue.add(unit);
    });
    this.drainSlowQueue(deadline);
  },

  drainSlowQueue(deadline) {
    const toHide = [];
    const now = performance.now();
    for (const unit of this.slowQueue) {
      if (deadline.timeRemaining() < 1) break;
      this.slowQueue.delete(unit);
      if (!unit.isConnected || unit.hasAttribute('data-clearbook-hidden')) continue;
      if (this.settled.has(unit)) continue;
      const old = now - this.seen(unit, now) > SETTLE_MS;
      const size = unit.getElementsByTagName('*').length;
      if (this.checked.get(unit) !== size) {
        this.checked.set(unit, size);
        const reason = this.classifyUnit(unit, true);
        if (reason) {
          toHide.push([unit, reason]);
          continue;
        }
      }
      // Old enough and checked thoroughly in its current state: done.
      if (old) this.settled.add(unit);
    }
    toHide.forEach(([unit, reason]) => this.hide(unit, reason, true));
    if (this.slowQueue.size > 0) {
      whenIdle(next => {
        try {
          this.drainSlowQueue(next);
        } catch (e) {
          console.error('Clearbook: cleanFeed failed', e);
        }
      });
    }
  },

  // When a unit was first seen (recording `now` if it's new).
  seen(unit, now) {
    let t = this.firstSeen.get(unit);
    if (t === undefined) {
      t = now;
      this.firstSeen.set(unit, t);
    }
    return t;
  },

  // The feed post containing `node`, or null if it isn't in one. Cached;
  // a cached unit that has since been removed from the page is recomputed.
  unitFor(node) {
    const cached = this.unitCache.get(node);
    if (cached === null || (cached && cached.isConnected)) return cached;
    const unit = this.findUnit(node);
    this.unitCache.set(node, unit);
    return unit;
  },

  findUnit(node) {
    if (this.hasLegacyLayout) {
      const legacy = node.closest(this.legacyUnitSelector);
      if (legacy) return legacy;
    }
    let post = node.closest('[aria-posinset]');
    if (!post) return null;
    // Use the top-level post if aria-posinset elements are nested.
    for (let up = post.parentElement && post.parentElement.closest('[aria-posinset]');
         up;
         up = up.parentElement && up.parentElement.closest('[aria-posinset]')) {
      post = up;
    }
    return this.outermostWrapper(post);
  },

  // Collect top-level feed posts (never comments or nested items).
  // Several layouts are supported because Facebook rolls out changes
  // gradually and different accounts see different markup.
  legacyUnitSelector: '[role="feed"] > div, [data-pagelet^="FeedUnit"]',

  getFeedUnits() {
    const units = new Set();
    const legacy = this.legacyUnitSelector;
    document.querySelectorAll(legacy).forEach(el => units.add(el));

    // Current layout (no role="feed"/"article"): each post contains a
    // div[aria-posinset], wrapped in a chain of single-child divs whose
    // top is a direct child of the feed list.
    document.querySelectorAll('[aria-posinset]').forEach(el => {
      if (el.parentElement && el.parentElement.closest('[aria-posinset]')) return;
      if (el.closest(legacy)) return;
      units.add(this.outermostWrapper(el));
    });

    // Fallback: top-level articles only (comments are nested articles).
    document.querySelectorAll('[role="article"]').forEach(article => {
      if (article.parentElement && article.parentElement.closest('[role="article"]')) return;
      if (article.closest(legacy) || article.closest('[aria-posinset]')) return;
      units.add(article);
    });
    return units;
  },

  // Climb through single-child wrappers so hiding a post doesn't leave its
  // empty wrapper (and spacing) behind. Stops at anything with siblings,
  // i.e. at the feed list item.
  outermostWrapper(el) {
    for (let i = 0; i < 20; i++) {
      const parent = el.parentElement;
      if (!parent || parent.childElementCount !== 1 || parent.matches(this.protectedSelector)) break;
      el = parent;
    }
    return el;
  },

  // Returns a reason string if the unit should be hidden, otherwise null.
  // `thorough` adds the expensive checks: hasObfuscatedText reads innerText
  // (forces a layout) and keyword matching reads the whole post's text.
  classifyUnit(unit, thorough) {
    const ps = this.providerSettings;
    const s = this.settings;
    const labels = this.collectLabels(unit);
    const hasLabel = list => list.some(l => labels.has(l.toLowerCase()));
    const hasMarker = list => list.some(sel => {
      try { return unit.querySelector(sel) !== null; } catch (e) { return false; }
    });

    if ((ps.hideSponsored || s.hideAds) &&
        (hasMarker(this.markers.sponsored) || hasLabel(this.labels.sponsored) ||
         this.hasReferencedText(unit, this.labels.sponsoredReferenced) ||
         (thorough && this.hasObfuscatedText(unit, this.labels.sponsored)))) {
      return 'sponsored';
    }
    if ((ps.hideSuggestedPosts || s.hideSuggestedContent) && hasLabel(this.labels.suggested)) {
      return 'suggested';
    }
    if (ps.hidePeopleYouMayKnow &&
        (hasMarker(this.markers.peopleYouMayKnow) || hasLabel(this.labels.peopleYouMayKnow))) {
      return 'people-you-may-know';
    }
    if ((ps.hideReels || s.hideReels) &&
        (hasMarker(this.markers.reels) || hasLabel(this.labels.reels))) {
      return 'reels';
    }
    if (ps.hideSuggestedGroups && hasLabel(this.labels.suggestedGroups)) {
      return 'suggested-groups';
    }
    if (ps.hideSuggestedPages && hasLabel(this.labels.suggestedPages)) {
      return 'suggested-pages';
    }
    if (s.hideAISlop && hasLabel(this.labels.ai)) {
      return 'ai';
    }
    if (s.friendsOnlyFeed && hasLabel(this.labels.nonFriend)) {
      return 'non-friend';
    }
    if (thorough && this.keywordBlacklist.length > 0) {
      const text = (unit.textContent || '').toLowerCase();
      if (this.keywordBlacklist.some(k => text.includes(k))) return 'keyword';
    }
    return null;
  },

  // Gather the trimmed, lower-cased text of short leaf-ish elements
  // (labels, buttons, headings). Uses textContent, which unlike innerText
  // doesn't force a layout.
  collectLabels(unit) {
    const labels = new Set();
    unit.querySelectorAll('span, a, h2, h3, h4, [role="button"]').forEach(el => {
      const t = el.textContent;
      if (t && t.length <= 60) labels.add(t.trim().toLowerCase());
    });
    unit.querySelectorAll('[aria-label]').forEach(el => {
      const t = el.getAttribute('aria-label');
      if (t && t.length <= 60) labels.add(t.trim().toLowerCase());
    });
    return labels;
  },

  // Facebook hides the "Sponsored" label from ad blockers. These helpers
  // cover the known tricks; see normalizeLabel/letterKey below.

  // Trick 1: the real label lives elsewhere in the document and is
  // referenced via aria-labelledby, or via SVG <use href="#id">. Facebook
  // chains <use> references (seen: 8 deep) before reaching the <text>.
  hasReferencedText(unit, list) {
    const wanted = list.map(normalizeLabel);
    const matches = el => !!el && wanted.includes(normalizeLabel(el.textContent || ''));
    for (const el of unit.querySelectorAll('[aria-labelledby]')) {
      const ids = el.getAttribute('aria-labelledby').split(/\s+/);
      if (ids.some(id => id && matches(document.getElementById(id)))) return true;
    }
    for (const use of unit.querySelectorAll('use')) {
      if (matches(resolveUseChain(use))) return true;
    }
    return false;
  },

  // Trick 2: the label is split into many single-letter spans, with decoy
  // letters hidden via CSS and/or the real letters shuffled in the DOM and
  // reordered visually. textContent sees the junk; innerText only returns
  // rendered text. Comparing sorted letters handles the shuffling.
  hasObfuscatedText(unit, list) {
    const wanted = list.map(normalizeLabel);
    const wantedKeys = wanted.map(letterKey);
    for (const el of unit.querySelectorAll('span, a')) {
      // Only small elements made of several pieces look like this.
      if (el.childElementCount < 3) continue;
      const raw = el.textContent;
      if (!raw || raw.length > 80) continue;
      const visible = normalizeLabel(el.innerText || '');
      if (visible.length < 5) continue;
      if (wanted.includes(visible) || wantedKeys.includes(letterKey(visible))) return true;
    }
    return false;
  },

  cleanRegions() {
    if (this.providerSettings.hideStories) {
      this.hideAll(this.regions.stories, 'stories');
    }
  },

  // Right-hand column "Sponsored" block. Its heading is plain text, and each
  // ad is a link carrying the `attributionsrc` attribute.
  cleanSidebarAds() {
    const ps = this.providerSettings;
    if (!(ps.hideSponsored || this.settings.hideAds)) return;
    const adLink = 'a[attributionsrc]';
    const adAny = 'a[attributionsrc], [aria-label*="sponsored content" i]';

    document.querySelectorAll('[role="complementary"]').forEach(side => {
      // Hide the whole section: the lowest ancestor of the "Sponsored"
      // heading that also contains an ad (never the sidebar itself).
      side.querySelectorAll('h2, h3, h4, [role="heading"]').forEach(h => {
        if (normalizeLabel(h.textContent || '') !== 'sponsored') return;
        let el = h.parentElement;
        while (el && el !== side && !el.querySelector(adAny)) el = el.parentElement;
        this.hide(el && el !== side ? el : childOf(side, h), 'sponsored');
      });
      // Ads not covered above: hide the largest wrapper holding only that ad.
      side.querySelectorAll(adLink).forEach(ad => {
        if (ad.closest('[data-clearbook-hidden]')) return;
        let el = ad;
        while (el.parentElement && el.parentElement !== side &&
               el.parentElement.querySelectorAll(adLink).length === 1) {
          el = el.parentElement;
        }
        this.hide(el, 'sponsored');
      });
    });
  },

  cleanNavLinks() {
    const ps = this.providerSettings;
    const s = this.settings;
    const scopes = '[role="navigation"], [role="banner"]';
    const hideIn = (sel, reason) => {
      document.querySelectorAll(scopes).forEach(scope => {
        scope.querySelectorAll(sel).forEach(a => this.hide(a.closest('li') || a, reason));
      });
    };
    if (ps.hideMarketplace || s.hideMarketplace) hideIn(this.navLinks.marketplace, 'marketplace');
    if (ps.hideWatch) hideIn(this.navLinks.watch, 'watch');
    if (ps.hideReels || s.hideReels) hideIn(this.navLinks.reels, 'reels');
  },

  hideAll(selectors, reason) {
    selectors.forEach(sel => {
      try {
        document.querySelectorAll(sel).forEach(el => this.hide(el, reason));
      } catch (e) {
        console.warn('Clearbook: invalid selector', sel, e);
      }
    });
  },

  // Hide via attribute (CSS in themes.css does display:none), refusing to
  // hide anything that would take out the page structure.
  // `collapse` (feed posts): if the "Show Hidden Post Markers" setting is
  // on, shrink to a thin labelled bar instead of removing it entirely, so
  // users can see what was filtered.
  hide(el, reason, collapse = false) {
    if (!el || el.hasAttribute('data-clearbook-hidden')) return;
    if (el.matches(this.protectedSelector) || el.querySelector(this.protectedSelector)) {
      return;
    }
    if (collapse && this.settings.showHiddenPlaceholders) {
      el.setAttribute('data-clearbook-collapsed', '');
    }
    el.setAttribute('data-clearbook-hidden', reason);
  },

  // With "Friends Only Feed" on, send the home feed to Facebook's own
  // friends feed. It only loads friends' posts, so there's far less to hide
  // and the feed doesn't keep running dry while Clearbook filters it.
  maybeRedirectToFriendsFeed() {
    if (!this.settings.friendsOnlyFeed || !this.providerSettings.enabled) return;
    const { pathname, search } = window.location;
    if (pathname !== '/' && pathname !== '/home.php') return;
    if (new URLSearchParams(search).get('filter') === 'friends') return;
    // Loop guard: if Facebook bounced us back to the plain home feed right
    // after a redirect (e.g. it changed the friends feed URL), don't retry
    // for a while; the regular friends-only filtering still applies.
    const key = 'clearbook-friends-redirect';
    const last = Number(sessionStorage.getItem(key) || 0);
    if (Date.now() - last < FRIENDS_REDIRECT_COOLDOWN_MS) return;
    sessionStorage.setItem(key, String(Date.now()));
    window.location.replace(FRIENDS_FEED_PATH);
  },

  // Unhide everything so changed settings take effect both ways.
  resetHidden() {
    document.querySelectorAll('[data-clearbook-hidden]')
      .forEach(el => {
        el.removeAttribute('data-clearbook-hidden');
        el.removeAttribute('data-clearbook-collapsed');
      });
    this.checked = new WeakMap();
    this.lastFastCheck = new WeakMap();
    this.firstSeen = new WeakMap();
    this.settled = new WeakSet();
  },

  updateSettings(newSettings) {
    this.applySettings(newSettings);
    this.maybeRedirectToFriendsFeed();
    if (!document.body) return;
    this.resetHidden();
    // Re-hide quickly with the cheap checks, then do a thorough sweep.
    this.getFeedUnits().forEach(unit => this.fastQueue.add(unit));
    this.scheduleFast();
    this.scheduleClean();
  },

  destroy() {
    if (this.observer) this.observer.disconnect();
    if (this.interval) clearInterval(this.interval);
  }
};

// Facebook's own friends-only feed (newest first).
const FRIENDS_FEED_PATH = '/?filter=friends&sk=h_chr';
const FRIENDS_REDIRECT_COOLDOWN_MS = 10000;

// Fast pass budget per animation frame, and minimum time between fast
// re-checks of the same post while Facebook is still filling it in.
const FAST_BUDGET_MS = 4;
const FAST_RECHECK_MS = 100;
// After this long on the page (and a clean thorough check), a post is
// considered settled and no longer checked. Ad/suggestion labels are
// present well before this.
const SETTLE_MS = 4000;

// Run `fn(deadline)` when the browser is idle (with a timeout so it can't
// be starved forever on a constantly busy page).
function whenIdle(fn) {
  if (typeof requestIdleCallback === 'function') {
    requestIdleCallback(fn, { timeout: 2000 });
  } else {
    setTimeout(() => fn({ timeRemaining: () => 8, didTimeout: true }), 50);
  }
}

// Lower-case letters only, so "Spon-so-red" / "S p o n s o r e d" match.
function normalizeLabel(text) {
  return text.toLowerCase().replace(/[^a-z]/g, '');
}

// Order-independent key for detecting shuffled letters.
function letterKey(text) {
  return [...text].sort().join('');
}

// Follow an SVG <use> through any chain of <use> references to the final
// element (e.g. a <text>). Returns null for broken chains or cycles.
function resolveUseChain(use) {
  const seen = new Set();
  let target = null;
  for (let hops = 0; use && hops < 20; hops++) {
    const href = use.getAttribute('href') || use.getAttribute('xlink:href') || '';
    if (!href.startsWith('#') || seen.has(href)) return null;
    seen.add(href);
    target = document.getElementById(href.slice(1));
    if (!target) return null;
    use = target.localName === 'use' ? target : target.querySelector('use');
  }
  return target;
}

// The ancestor of `el` that is a direct child of `root` (or null).
function childOf(root, el) {
  while (el && el.parentElement !== root) el = el.parentElement;
  return el;
}

// Content scripts run at document_start, before <body> exists.
function whenBodyReady() {
  if (document.body) return Promise.resolve();
  return new Promise(resolve => {
    const check = () => {
      if (document.body) {
        obs.disconnect();
        resolve();
      }
    };
    const obs = new MutationObserver(check);
    obs.observe(document.documentElement, { childList: true });
    check();
  });
}

(async () => {
  try {
    const settings = await ClearbookStorage.getSettings();
    await FacebookProvider.init(settings);

    browser.storage.onChanged.addListener((changes, area) => {
      if (area === 'sync' && changes.settings && changes.settings.newValue) {
        FacebookProvider.updateSettings(ClearbookStorage.withDefaults(changes.settings.newValue));
      }
    });
  } catch (e) {
    console.error('Clearbook: Failed to initialize Facebook provider', e);
  }
})();
